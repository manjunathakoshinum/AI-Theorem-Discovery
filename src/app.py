def load_and_run_model(prompt, task, domain, retries=3):
    for attempt in range(retries):
        try:
            if not os.path.exists(GGUF_PATH):
                raise FileNotFoundError(f"Model not found at: {GGUF_PATH}")
            logging.info(f"Attempt {attempt + 1}: Loading model for {task} in {domain}...")
            model = Llama(model_path=GGUF_PATH, n_ctx=4096, verbose=True)
            logging.info(f"Attempt {attempt + 1}: Model loaded.")
            logging.debug(f"Prompt: {prompt}")
            output = model(prompt, max_tokens=4000, temperature=0.7, top_p=0.95)["choices"][0]["text"].strip()
            logging.debug(f"Raw output: {output[:200]}...")
            if not output or output.isspace():
                logging.warning(f"Attempt {attempt + 1}: Model returned empty output.")
                if attempt == retries - 1:
                    return "No output generated by the model after multiple attempts."
                continue
            logging.info(f"Attempt {attempt + 1}: Output generated successfully.")
            return output
        except Exception as e:
            logging.error(f"Attempt {attempt + 1}: Model error: {e}")
            if attempt == retries - 1:
                return f"Error: {str(e)}"
    return "No output generated by the model after multiple attempts."

def save_output(response, task, domain, problem, discipline):
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    filename = os.path.join(app.config['UPLOAD_FOLDER'], f"output_{task}_{domain}_{timestamp}.json")
    try:
        output_data = {
            "task": task,
            "domain": domain,
            "problem": problem,
            "discipline": discipline,
            "timestamp": timestamp,
            "response": response
        }
        with open(filename, "w", encoding="utf-8") as f:
            json.dump(output_data, f, indent=2, ensure_ascii=False)
        logging.info(f"Output saved to {filename}")
        return filename
    except Exception as e:
        logging.error(f"Save error: {e}")
        return None

@app.route('/')
def index():
    return render_template('index.html')

@app.route('/process', methods=['POST'])
def process():
    try:
        task = request.form.get('task', 'prove')
        domain = request.form.get('domain', 'hyperbolic_geometry')
        style = request.form.get('style', 'unconventional')
        problem = request.form.get('problem', '')
        discipline = request.form.get('discipline', '')

        logging.info(f"Processing task: {task}, domain: {domain}, style: {style}, problem: {problem}, discipline: {discipline}")

        if task not in PROMPTS:
            return jsonify({'error': f'Invalid task: {task}'}), 400

        if task == 'refine':
            refine_file = request.files.get('refine_file')
            if not refine_file:
                return jsonify({'error': 'No file provided for refinement'}), 400
            filename = secure_filename(refine_file.filename)
            file_path = os.path.join(app.config['UPLOAD_FOLDER'], filename)
            refine_file.save(file_path)
            with open(file_path, 'r', encoding='utf-8') as f:
                previous_output = f.read() if not filename.endswith('.json') else json.load(f).get('response', '')
            prompt = PROMPTS[task].format(output=previous_output, domain=domain, style=style)
        else:
            prompt = PROMPTS[task].format(problem=problem, domain=domain, style=style, discipline=discipline)

        output = load_and_run_model(prompt, task, domain)
        saved_file = save_output(output, task, domain, problem, discipline)
        socketio.emit('new_message', {'task': task, 'domain': domain, 'output': output})
        return jsonify({
            'output': output,
            'saved_file': saved_file
        })
    except Exception as e:
        logging.error(f"Process error: {e}")
        return jsonify({'error': str(e)}), 500

if __name__ == '__main__':
    socketio.run(app, debug=True)