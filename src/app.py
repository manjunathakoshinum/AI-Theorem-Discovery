app = Flask(__name__)
app.config['UPLOAD_FOLDER'] = 'Uploads'
os.makedirs(app.config['UPLOAD_FOLDER'], exist_ok=True)
socketio = SocketIO(app)

# Configure logging
logging.basicConfig(filename='math_discovery_web.log', level=logging.DEBUG, 
                    format='%(asctime)s - %(levelname)s - %(message)s')

# Path to the GGUF file
GGUF_PATH = os.path.join("model", "DeepSeek-Prover-V1.5-RL.Q4_K_S.gguf")

